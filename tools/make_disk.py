#!/usr/bin/env python3
"""Pack the zOS setup disk (disk/) into one Lua program that writes it onto a floppy.

Upload the result to Pastebin, then in game, with a floppy in a disk drive:

    pastebin run <code>                 # writes the setup disk to the first floppy found
    pastebin run <code> <side>          # or to the floppy in the drive on that side
    pastebin run <code> <folder>        # or to a folder instead of a floppy

The disk it writes is the normal setup disk: install zOS from it as usual.

File contents are stored as escaped Lua strings, one per line, so the program
survives Pastebin's line-ending conversion and whitespace changes byte for byte.
"""

import argparse
import datetime
import os
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DISK = os.path.join(ROOT, "disk")
DEFAULT_OUT = os.path.join(ROOT, "dist", "zos-disk.lua")

# CC: Tweaked counts every file and folder as at least this many bytes of disk space.
MIN_FILE_SIZE = 500
PASTEBIN_LIMIT = 512 * 1024  # largest paste on a free account


def read_version():
    with open(os.path.join(DISK, "payload", "zos", "boot.lua"), encoding="ascii") as f:
        for line in f:
            if line.startswith("local VERSION = "):
                return line.split('"')[1]
    return "?"


def collect_files(root=DISK, prefix=""):
    """Every file under root, as (prefix + posix path relative to root, bytes), sorted by path."""
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for name in filenames:
            if name.startswith("."):
                continue
            full = os.path.join(dirpath, name)
            rel = prefix + os.path.relpath(full, root).replace(os.sep, "/")
            with open(full, "rb") as f:
                files.append((rel, f.read()))
    files.sort()
    return files


def lua_string(data):
    """A double-quoted Lua string for these bytes, using only printable ASCII."""
    out = ['"']
    for b in data:
        c = chr(b)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif 0x20 <= b <= 0x7E:
            out.append(c)
        else:
            out.append("\\%03d" % b)  # always 3 digits, so a following digit isn't absorbed
    out.append('"')
    return "".join(out)


def space_needed(files):
    dirs = set()
    for path, _ in files:
        parts = path.split("/")[:-1]
        for i in range(1, len(parts) + 1):
            dirs.add("/".join(parts[:i]))
    return sum(max(len(data), MIN_FILE_SIZE) for _, data in files) + MIN_FILE_SIZE * len(dirs)


def build(files, *, title, label, header, finish):
    """A Lua program that writes files onto a floppy labelled label.

    header is a list of comment lines for the top of the program, finish a Lua snippet run
    after everything is written (TARGET and DRIVE are in scope).
    """
    out = [f"-- {line}".rstrip() for line in header] + [
        "",
        f"local TITLE = {lua_string(title.encode())}",
        f"local LABEL = {lua_string(label.encode())}",
        f"local SPACE = {space_needed(files)} -- bytes the files take up on a disk",
        "",
        "-- Each file is a list of lines; they're joined with newlines when written.",
        "local FILES = {",
    ]
    for path, data in files:
        out.append(f"  {{ path = {lua_string(path.encode())}, size = {len(data)}, lines = {{")
        for line in data.split(b"\n"):
            out.append("    " + lua_string(line) + ",")
        out.append("  } },")
    out.append("}")
    out.append(WRITER)
    out.append(finish.strip("\n"))
    return "\n".join(out) + "\n"


def usage_lines(program):
    return [
        f"Usage: {program}            the first floppy found in a disk drive",
        f"       {program} <side>     the floppy in the drive on that side (or peripheral name)",
        f"       {program} <folder>   a folder instead of a floppy",
    ]


def build_setup(files, version):
    today = datetime.date.today().isoformat()
    header = [
        f"zOS {version} setup disk writer. Generated by tools/make_disk.py on {today}.",
        "Writes the zOS setup disk onto a floppy, which you then install zOS from.",
        "",
    ] + usage_lines("zos-disk")
    return build(files, title=f"zOS {version} setup disk writer", label=f"zOS Setup {version}",
                 header=header, finish=SETUP_FINISH)


SETUP_FINISH = r"""
print("Setup disk ready" .. (DRIVE and (" and labelled \"" .. LABEL .. "\"") or "") .. ".")
print("To install zOS, put it in a drive next to the target computer and reboot that")
print("computer, or run /" .. fs.combine(TARGET, "install") .. " here.")
"""


WRITER = r"""
local arg = ({ ... })[1]

local function fail(message)
  printError(message)
end

local function drives()
  local names = {}
  for _, name in ipairs(peripheral.getNames()) do
    if peripheral.getType(name) == "drive" then names[#names + 1] = name end
  end
  return names
end

-- Work out where to write: TARGET is a folder, DRIVE the drive holding it (if any).
local TARGET, DRIVE
if arg and peripheral.getType(arg) == "drive" then
  DRIVE = arg
elseif arg then
  TARGET = fs.combine(arg, "")
  for _, name in ipairs(drives()) do
    if disk.getMountPath(name) == TARGET then DRIVE = name end
  end
else
  for _, name in ipairs(drives()) do
    if disk.hasData(name) then
      DRIVE = name
      break
    end
  end
  if not DRIVE then return fail("No floppy found. Put a floppy disk in a disk drive and run this again.") end
end
if DRIVE then
  if not disk.hasData(DRIVE) then return fail("The drive '" .. DRIVE .. "' has no floppy disk in it.") end
  TARGET = disk.getMountPath(DRIVE)
end

if TARGET == "" then return fail("Refusing to write over this computer's own files. Name a floppy or a folder.") end
if fs.exists(TARGET) and not fs.isDir(TARGET) then return fail(TARGET .. " is a file, not a folder.") end
if fs.isReadOnly(TARGET) then return fail(TARGET .. " is read-only.") end

print(TITLE)
print("Writing to /" .. TARGET .. (DRIVE and (" (drive " .. DRIVE .. ")") or ""))

-- Old files would be mixed in with the new ones, so the target has to be emptied first.
local existing = fs.exists(TARGET) and fs.list(TARGET) or {}
if #existing > 0 then
  print("")
  print("/" .. TARGET .. " already contains " .. #existing .. " item(s):")
  print("  " .. table.concat(existing, " "))
  write("Erase everything on it? (y/n) ")
  local answer = read()
  if answer:lower():sub(1, 1) ~= "y" then
    print("Cancelled. Nothing was changed.")
    return
  end
  for _, name in ipairs(existing) do fs.delete(fs.combine(TARGET, name)) end
end

fs.makeDir(TARGET)
local free = fs.getFreeSpace(TARGET)
if free ~= "unlimited" and free < SPACE then
  return fail(("This disk needs %.0f KB but only %.0f KB is free."):format(SPACE / 1024, free / 1024))
end

for i, file in ipairs(FILES) do
  local path = fs.combine(TARGET, file.path)
  local data = table.concat(file.lines, "\n")
  if #data ~= file.size then return fail("This program is damaged (" .. file.path .. "). Download it again.") end

  fs.makeDir(fs.getDir(path))
  local f, err = fs.open(path, "wb")
  if not f then return fail("Can't write " .. path .. ": " .. tostring(err)) end
  f.write(data)
  f.close()

  -- Read it back to catch a full disk or a failed write.
  f = fs.open(path, "rb")
  local written = f and f.readAll()
  if f then f.close() end
  if written ~= data then return fail("Writing " .. path .. " failed. Is the disk full?") end

  print(("[%2d/%d] %s"):format(i, #FILES, file.path))
end

if DRIVE then pcall(disk.setLabel, DRIVE, LABEL) end

print("")"""


def upload(text, name, dev_key, public):
    body = urllib.parse.urlencode({
        "api_dev_key": dev_key,
        "api_option": "paste",
        "api_paste_code": text,
        "api_paste_name": name,
        "api_paste_format": "lua",
        "api_paste_private": "0" if public else "1",  # 1 = unlisted
    }).encode()
    with urllib.request.urlopen("https://pastebin.com/api/api_post.php", body, timeout=60) as resp:
        result = resp.read().decode().strip()
    if not result.startswith("http"):
        sys.exit(f"Pastebin upload failed: {result}")
    return result.rsplit("/", 1)[-1]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", default=DEFAULT_OUT, help="where to write the program (default: dist/zos-disk.lua)")
    parser.add_argument("--upload", action="store_true", help="also upload it to Pastebin (needs PASTEBIN_DEV_KEY)")
    parser.add_argument("--public", action="store_true", help="with --upload: make the paste public instead of unlisted")
    args = parser.parse_args()

    files = collect_files()
    version = read_version()
    text = build_setup(files, version)

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="ascii", newline="\n") as f:
        f.write(text)

    total = sum(len(d) for _, d in files)
    print(f"Wrote {os.path.relpath(args.output)}: zOS {version}, {len(files)} files, "
          f"{total / 1024:.0f} KB of files, {len(text) / 1024:.0f} KB program")
    if len(text) > PASTEBIN_LIMIT:
        print(f"Warning: that's over Pastebin's {PASTEBIN_LIMIT // 1024} KB limit for free accounts.")

    if args.upload:
        dev_key = os.environ.get("PASTEBIN_DEV_KEY")
        if not dev_key:
            sys.exit("Set PASTEBIN_DEV_KEY to your Pastebin API key (https://pastebin.com/doc_api).")
        code = upload(text, f"zOS {version} setup disk", dev_key, args.public)
        print(f"Uploaded to https://pastebin.com/{code}")
        print(f"In game, with a floppy in a disk drive:  pastebin run {code}")
    else:
        print("Upload it to Pastebin, then in game, with a floppy in a disk drive:  pastebin run <code>")


if __name__ == "__main__":
    main()
