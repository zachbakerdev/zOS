#!/usr/bin/env python3
"""Pack each app in apps/ into a Lua program that writes it onto a floppy.

For every apps/<id>/ (zos-mail, zos-notes, ...) this writes dist/<id>-disk.lua. Upload one
to Pastebin, then in game, with a floppy in a disk drive:

    pastebin run <code>                 # writes the app disk to the first floppy found
    pastebin run <code> <side>          # or to the floppy in the drive on that side
    pastebin run <code> <folder>        # or to a folder instead of a floppy

The disk holds the app's folder (e.g. notes/), so it installs with the App Manager app or
`appman install disk/notes` on the zOS computer.

Uses the same writer as tools/make_disk.py, so the same Pastebin-safety and checks apply.
"""

import argparse
import datetime
import os
import re
import sys

from make_disk import PASTEBIN_LIMIT, ROOT, build, collect_files, lua_string, upload, usage_lines

APPS = os.path.join(ROOT, "apps")
DEFAULT_OUT_DIR = os.path.join(ROOT, "dist")

FINISH = r"""
print("App disk ready" .. (DRIVE and (" and labelled \"" .. LABEL .. "\"") or "") .. ".")
print("To install " .. APP_NAME .. ", put it in a drive next to the zOS computer and")
print("use the App Manager app, or run this in the Shell:")
print("  appman install " .. (DRIVE and fs.combine("disk", APP_FOLDER) or fs.combine(TARGET, APP_FOLDER)))
if DRIVE then print("(use the disk's mount path if it isn't 'disk')") end
"""


def manifest_field(text, key):
    match = re.search(r"\b" + key + r'\s*=\s*"((?:[^"\\]|\\.)*)"', text)
    return match.group(1) if match else None


def find_apps():
    """Every apps/<id>/ holding exactly one app folder, as dicts sorted by id."""
    apps = []
    for app_id in sorted(os.listdir(APPS)):
        base = os.path.join(APPS, app_id)
        if app_id.startswith(".") or not os.path.isdir(base):
            continue
        folders = [d for d in sorted(os.listdir(base))
                   if os.path.isfile(os.path.join(base, d, "app.manifest"))]
        if len(folders) != 1:
            print(f"Skipping apps/{app_id}: expected one folder with an app.manifest, found {len(folders)}",
                  file=sys.stderr)
            continue
        folder = folders[0]
        with open(os.path.join(base, folder, "app.manifest"), encoding="utf-8") as f:
            manifest = f.read()
        apps.append({
            "id": app_id,
            "folder": folder,
            "path": os.path.join(base, folder),
            "name": manifest_field(manifest, "name") or folder,
            "version": manifest_field(manifest, "version") or "?",
        })
    return apps


def build_app(app, files):
    today = datetime.date.today().isoformat()
    name, version, folder = app["name"], app["version"], app["folder"]
    header = [
        f"zOS {name} {version} app disk writer. Generated by tools/make_app_disks.py on {today}.",
        f"Writes the {name} app onto a floppy, which you then install it from with appman.",
        "",
    ] + usage_lines(f"{app['id']}-disk")
    finish = "\n".join([
        f"local APP_NAME = {lua_string(name.encode())}",
        f"local APP_FOLDER = {lua_string(folder.encode())}",
        FINISH,
    ])
    return build(files, title=f"zOS {name} {version} app disk writer", label=f"zOS {name} {version}",
                 header=header, finish=finish)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("apps", nargs="*", metavar="app",
                        help="apps to build, e.g. notes or zos-notes (default: all)")
    parser.add_argument("-o", "--output-dir", default=DEFAULT_OUT_DIR, help="where to write the programs (default: dist/)")
    parser.add_argument("--upload", action="store_true", help="also upload each one to Pastebin (needs PASTEBIN_DEV_KEY)")
    parser.add_argument("--public", action="store_true", help="with --upload: make the pastes public instead of unlisted")
    args = parser.parse_args()

    apps = find_apps()
    if args.apps:
        wanted = {a if a.startswith("zos-") else "zos-" + a for a in args.apps}
        unknown = wanted - {app["id"] for app in apps}
        if unknown:
            sys.exit(f"Unknown app(s): {', '.join(sorted(unknown))}. "
                     f"Available: {', '.join(app['id'] for app in apps)}")
        apps = [app for app in apps if app["id"] in wanted]

    dev_key = os.environ.get("PASTEBIN_DEV_KEY")
    if args.upload and not dev_key:
        sys.exit("Set PASTEBIN_DEV_KEY to your Pastebin API key (https://pastebin.com/doc_api).")

    os.makedirs(args.output_dir, exist_ok=True)
    for app in apps:
        files = collect_files(app["path"], app["folder"] + "/")
        text = build_app(app, files)
        out = os.path.join(args.output_dir, f"{app['id']}-disk.lua")
        with open(out, "w", encoding="ascii", newline="\n") as f:
            f.write(text)

        total = sum(len(d) for _, d in files)
        print(f"Wrote {os.path.relpath(out)}: {app['name']} {app['version']}, {len(files)} files, "
              f"{total / 1024:.0f} KB of files, {len(text) / 1024:.0f} KB program")
        if len(text) > PASTEBIN_LIMIT:
            print(f"  Warning: that's over Pastebin's {PASTEBIN_LIMIT // 1024} KB limit for free accounts.")

        if args.upload:
            code = upload(text, f"zOS {app['name']} {app['version']} app disk", dev_key, args.public)
            print(f"  Uploaded to https://pastebin.com/{code}  (in game: pastebin run {code})")

    if apps and not args.upload:
        print("Upload one to Pastebin, then in game, with a floppy in a disk drive:  pastebin run <code>")


if __name__ == "__main__":
    main()
